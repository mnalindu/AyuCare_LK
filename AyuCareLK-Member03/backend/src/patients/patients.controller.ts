import { Body, Controller, Get, Param, ParseUUIDPipe, Patch, Post, Query } from '@nestjs/common';
import { ApiBadRequestResponse, ApiBearerAuth, ApiConflictResponse, ApiCreatedResponse, ApiForbiddenResponse, ApiNotFoundResponse, ApiOkResponse, ApiOperation, ApiParam, ApiQuery, ApiTags, ApiUnauthorizedResponse } from '@nestjs/swagger';
import { CurrentUser } from '../auth/current-user.decorator';
import { StaffProfileDto } from '../auth/dto/login-response.dto';
import { Roles } from '../auth/roles.decorator';
import { StaffRole } from '../auth/roles';
import { CreatePatientDto } from './dto/create-patient.dto';
import { ListPatientsQueryDto } from './dto/list-patients-query.dto';
import { PatientListResponseDto, PatientResponseDto } from './dto/patient-response.dto';
import { UpdatePatientDto } from './dto/update-patient.dto';
import { PatientsService } from './patients.service';

@ApiTags('Patients')
@ApiBearerAuth()
@ApiUnauthorizedResponse({ description: 'Missing, invalid, or expired bearer token' })
@ApiForbiddenResponse({ description: 'Staff role is not permitted' })
@Roles(StaffRole.SUPER_ADMIN, StaffRole.CLINIC_ADMIN, StaffRole.RECEPTIONIST, StaffRole.DOCTOR)
@Controller('patients')
export class PatientsController {
  constructor(private readonly patients: PatientsService) {}

  @Post()
  @Roles(StaffRole.SUPER_ADMIN, StaffRole.CLINIC_ADMIN, StaffRole.RECEPTIONIST)
  @ApiOperation({ summary: 'Register a patient', description: 'Requires SUPER_ADMIN, CLINIC_ADMIN, or RECEPTIONIST. Patient ID and number are generated by the server.' })
  @ApiCreatedResponse({ type: PatientResponseDto })
  @ApiBadRequestResponse({ description: 'Invalid demographic or contact fields' })
  @ApiConflictResponse({ description: 'A likely duplicate patient or identifier conflict' })
  create(@Body() input: CreatePatientDto, @CurrentUser() staff: StaffProfileDto): Promise<PatientResponseDto> {
    return this.patients.create(input, staff.id);
  }

  @Get()
  @ApiOperation({ summary: 'List and search patients', description: 'Requires SUPER_ADMIN, CLINIC_ADMIN, RECEPTIONIST, or DOCTOR.' })
  @ApiQuery({ name: 'page', required: false, type: Number, example: 1 })
  @ApiQuery({ name: 'limit', required: false, type: Number, example: 20 })
  @ApiQuery({ name: 'search', required: false, type: String, description: 'Full name, UUID, or patient number' })
  @ApiOkResponse({ type: PatientListResponseDto })
  @ApiBadRequestResponse({ description: 'Invalid pagination or search parameter' })
  findAll(@Query() query: ListPatientsQueryDto): Promise<PatientListResponseDto> { return this.patients.findAll(query); }

  @Get(':id')
  @ApiOperation({ summary: 'Get a patient by UUID' })
  @ApiParam({ name: 'id', format: 'uuid' })
  @ApiOkResponse({ type: PatientResponseDto })
  @ApiBadRequestResponse({ description: 'Invalid UUID' })
  @ApiNotFoundResponse({ description: 'Patient not found' })
  findOne(@Param('id', new ParseUUIDPipe()) id: string): Promise<PatientResponseDto> { return this.patients.findOne(id); }

  @Patch(':id')
  @Roles(StaffRole.SUPER_ADMIN, StaffRole.CLINIC_ADMIN, StaffRole.RECEPTIONIST)
  @ApiOperation({ summary: 'Update patient demographics and contact details', description: 'Requires SUPER_ADMIN, CLINIC_ADMIN, or RECEPTIONIST. Patient IDs, status, and registrar cannot be changed.' })
  @ApiParam({ name: 'id', format: 'uuid' })
  @ApiOkResponse({ type: PatientResponseDto })
  @ApiBadRequestResponse({ description: 'Invalid UUID or update body' })
  @ApiNotFoundResponse({ description: 'Patient not found' })
  @ApiConflictResponse({ description: 'Update conflicts with an existing record' })
  update(@Param('id', new ParseUUIDPipe()) id: string, @Body() input: UpdatePatientDto): Promise<PatientResponseDto> {
    return this.patients.update(id, input);
  }
}
