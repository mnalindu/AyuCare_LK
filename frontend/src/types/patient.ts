/**
 * Core Patient entity matching NestJS PatientResponseDto.
 */
export interface Patient {
  id: string;               // UUID v4
  patientNumber: number;    // Numeric sequential ID generated by server
  fullName: string;         // 1..200 chars
  dateOfBirth: string | null; // ISO YYYY-MM-DD
  phone: string | null;     // 7..15 digits, optional +
  email: string | null;     // max 254 chars
  address: string | null;   // max 1000 chars
  isActive: boolean;
  createdAt: string;        // ISO timestamp
  updatedAt: string;        // ISO timestamp
}

/**
 * Paginated patient list response matching NestJS PatientListResponseDto.
 */
export interface PatientListResponse {
  items: Patient[];
  page: number;
  limit: number;
  total: number;
  totalPages: number;
}

/**
 * Payload for registering a new patient matching NestJS CreatePatientDto.
 */
export interface CreatePatientInput {
  fullName: string;
  dateOfBirth?: string | null;
  phone?: string | null;
  email?: string | null;
  address?: string | null;
}

/**
 * Payload for updating an existing patient matching NestJS UpdatePatientDto.
 */
export type UpdatePatientInput = Partial<CreatePatientInput>;

/**
 * Query filters for searching and paginating patients.
 */
export interface PatientQueryParams {
  page?: number;
  limit?: number;
  search?: string;
}

